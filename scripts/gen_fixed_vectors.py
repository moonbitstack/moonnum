#!/usr/bin/env python3
"""Generate `src/fixed_vectors_wbtest.mbt` from mpmath.

The tests in this repository only read what this script writes; no test runs
Python. Regenerate with `python3 scripts/gen_fixed_vectors.py` after changing
the reference, and expect to review the diff: every changed line is a behaviour
change.

The reference is mpmath 1.4. Each expected value is printed with a hair more
than the digits a fifty-digit width speaks for, so the test reads it back with
`of_decimal` and compares with a margin that is absolute for a small answer and
relative for a large one: `Fixed` truncates to a grid of one over two to the
power of its bits, and the error that carries is that grid step times the size
of the answer, so the margin grows with the answer too.
"""

from __future__ import annotations

import sys

import mpmath as mp

# A value's exact decimal runs to a digit for every three and a third bits, and
# the vectors carry values of hundreds of digits.
sys.set_int_max_str_digits(0)

OUT = "src/fixed_vectors_wbtest.mbt"

# The width the vectors are checked at: fifty digits, the width the handwritten
# fixed-point tests already use. `bits_for_digits(50)` is the number of
# fractional bits that holds that many of them.
DIGITS = 50
# The digits the reference is printed to: a few more than the width checks, so
# the margin below is about the two implementations and not about the reading.
REFERENCE_DIGITS = 52


def esc(text: str) -> str:
    """A MoonBit string literal holding `text`."""
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def reference(text: str) -> str:
    """`text` as the decimal the reference answers for it, at the printed width."""
    with mp.workprec(1200):
        return mp.nstr(
            mp.mpf(text), REFERENCE_DIGITS, strip_zeros=True,
        )


def answer(fn, text: str) -> str:
    """`fn` of `text`, at the precision the reference answers at, printed wide."""
    with mp.workprec(1200):
        value = fn(mp.mpf(text))
        if mp.isinf(value) or mp.isnan(value):
            raise AssertionError(f"{fn.__name__}({text}) is not finite: {value}")
        return mp.nstr(value, REFERENCE_DIGITS, strip_zeros=True)


# Arguments a small width must keep honest: near zero, where `exp(x) - 1` and
# `ln(1 + x)` both round to zero when spelt the long way; moderate, where the
# series is the answer; and far from zero, where one of the two is the ordinary
# function and the other has settled against one.
EXPM1_ARGUMENTS = [
    "0",
    "1e-40",
    "1e-20",
    "1e-8",
    "1e-4",
    "0.5",
    "-0.5",
    "1",
    "-1",
    "10",
    "-10",
    "100",
    "-100",
]

LOG1P_ARGUMENTS = [
    "0",
    "1e-40",
    "1e-20",
    "1e-8",
    "1e-4",
    "0.5",
    "-0.5",
    "1",
    "-0.9999999999999999",
    "10",
    "1e10",
    "-1e-16",
]


def rows(fn, arguments: list[str]) -> list[str]:
    lines = []
    for arg in arguments:
        lines.append("    (%s, %s)," % (esc(arg), esc(answer(fn, arg))))
    return lines


def main() -> int:
    out: list[str] = [
        "// Generated by scripts/gen_fixed_vectors.py from mpmath. Do not edit.",
        "// Every row is an argument and what the reference answers for it; the",
        "// test reads it back and compares within the width's margin.",
        "",
        "let vector_bits : Int32 = Fixed::bits_for_digits(%d)" % DIGITS,
        "",
        "let vector_margin : Fixed = Fixed::of_scaled(\"1\", %d, vector_bits)"
        % (DIGITS - 5),
        "",
        "///|",
        "/// Close when the gap is within the margin: absolute for a small",
        "/// answer, and growing with the answer for a large one, because the",
        "/// fixed-point grid costs a step of the answer's own size.",
        "fn vector_close(got : Fixed, want : Fixed) -> Bool {",
        "  (got - want).abs() <= vector_margin + vector_margin * want.abs()",
        "}",
        "",
        '///|',
        'test "expm1 agrees with mpmath at fifty digits" {',
        "  for (arg, want) in [",
    ]
    out.extend(rows(mp.expm1, EXPM1_ARGUMENTS))
    out.extend([
        "  ] {",
        "    let got = Fixed::of_decimal(arg, vector_bits).expm1()",
        "    let want_value = Fixed::of_decimal(want, vector_bits)",
        "    assert_true(vector_close(got, want_value))",
        "  }",
        "}",
        "",
        '///|',
        'test "log1p agrees with mpmath at fifty digits" {',
        "  for (arg, want) in [",
    ])
    out.extend(rows(mp.log1p, LOG1P_ARGUMENTS))
    out.extend([
        "  ] {",
        "    let got = Fixed::of_decimal(arg, vector_bits).log1p()",
        "    let want_value = Fixed::of_decimal(want, vector_bits)",
        "    assert_true(vector_close(got, want_value))",
        "  }",
        "}",
        "",
    ])

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print(f"wrote {OUT}: {len(out)} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
